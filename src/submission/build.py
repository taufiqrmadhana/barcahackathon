"""Build Borrow Khan's technical PDF and an editable Overleaf source archive.

Metrics come from the committed checkpoint report. Restricted match assets are
not needed to typeset the document and are never copied into the output archive.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
REPORT = ROOT / 'src/bench/results/macro_v5_2026-11-16.json'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--engine', help='path to tectonic or pdflatex')
    ap.add_argument('--out', type=Path, default=HERE / 'build')
    ap.add_argument('--plot-python', help='Python interpreter with matplotlib installed')
    args = ap.parse_args()
    report = json.loads(REPORT.read_text())
    public = report['checkpoint']['public']
    digest = report['sha256']['evaluation/results/barca.csv']
    metrics = ('% Generated by build.py from the committed macro-v5 report.\n'
               f'\\newcommand{{\\MacroScore}}{{{public["macro_f1"]:.6f}}}\n'
               f'\\newcommand{{\\SpellScore}}{{{public["spell_f1_mean"]:.6f}}}\n'
               f'\\newcommand{{\\CSVHashFirst}}{{{digest[:32]}}}\n'
               f'\\newcommand{{\\CSVHashLast}}{{{digest[32:]}}}\n')
    local_csv = ROOT / 'evaluation/results/barca.csv'
    if local_csv.exists() and hashlib.sha256(local_csv.read_bytes()).hexdigest() != digest:
        raise SystemExit('Local barca.csv differs from the frozen checkpoint; review the report before building.')
    (HERE / 'metrics.tex').write_text(metrics)
    output = args.out.resolve()
    output.mkdir(parents=True, exist_ok=True)
    for name in ('Borrow_Khan.tex', 'team.tex', 'metrics.tex'):
        shutil.copyfile(HERE / name, output / name)
    plot_python = args.plot_python
    if not plot_python:
        if importlib.util.find_spec('matplotlib'):
            plot_python = sys.executable
        elif (ROOT / '.venv-cv/bin/python').exists():
            plot_python = str(ROOT / '.venv-cv/bin/python')
        else:
            raise SystemExit('Install src/submission/requirements.txt, or provide --plot-python.')
    plots = subprocess.run([plot_python, str(HERE / 'figures.py'), '--report', str(REPORT),
                            '--out', str(output / 'figures')], text=True, capture_output=True)
    if plots.returncode:
        raise SystemExit(plots.stdout + plots.stderr)
    local_engine = ROOT / 'cache/document_tools/tectonic'
    engine = (args.engine or shutil.which('tectonic')
              or (str(local_engine) if local_engine.exists() else None)
              or shutil.which('pdflatex'))
    if not engine:
        raise SystemExit('Install Tectonic or pdfLaTeX, or provide --engine /path/to/compiler.')
    engine = str(Path(engine).resolve())
    if Path(engine).name.startswith('tectonic'):
        command = [engine, '--untrusted', '--keep-logs', 'Borrow_Khan.tex']
        passes = 1
    else:
        command = [engine, '-interaction=nonstopmode', '-halt-on-error', 'Borrow_Khan.tex']
        passes = 2
    log = []
    for _ in range(passes):
        result = subprocess.run(command, cwd=output, text=True, capture_output=True)
        log.append(result.stdout + result.stderr)
        (output / 'build.engine.log').write_text('\n'.join(log))
        if result.returncode:
            raise SystemExit('\n'.join(log)[-18000:])
    pdf = output / 'Borrow_Khan.pdf'
    if not pdf.exists():
        raise SystemExit('Compiler did not produce Borrow_Khan.pdf.')
    with zipfile.ZipFile(output / 'Borrow_Khan_Overleaf.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
        for name in ('Borrow_Khan.tex', 'team.tex', 'metrics.tex',
                     'figures/ablation.pdf', 'figures/fold_sensitivity.pdf',
                     'figures/match_statistics.pdf', 'figures/data.json'):
            archive.write(output / name, name)
        archive.writestr('README.txt',
            'Main document: Borrow_Khan.tex. Compile with pdfLaTeX.\n'
            'Four-page visual technical report. Standard TeX Live/Overleaf packages.\n'
            'Figures are vector PDFs generated from aggregate checkpoint metrics.\n'
            'Edit team.tex for author information. Metrics refer to code b8e4ad0.\n')
    print(f'PDF: {pdf}')
    print(f'Editable source: {output / "Borrow_Khan_Overleaf.zip"}')
    print(f'Checkpoint: macroF1 {public["macro_f1"]:.6f}, spellF1 {public["spell_f1_mean"]:.6f}')


if __name__ == '__main__':
    main()
